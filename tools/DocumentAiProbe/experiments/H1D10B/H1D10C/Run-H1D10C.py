#!/usr/bin/env python3
"""H1D10C - Perception audit for the H1D10B Top150 queue.

Diagnostic only. It does not train, score or promote models and does not alter
H1D10A/H1D10B artifacts. It reads the local text assets generated by H1D10A,
reproduces the current strict title rule, and measures where useful lexical
cues exist relative to that rule.

The ChatGPT blind visual classification is used only as a diagnostic reference,
never as production ground truth.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import sys
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPERIMENTS = HERE.parent
H1D10A = EXPERIMENTS / "H1D10A"
H1D10B = EXPERIMENTS / "H1D10B"
DEFAULT_OUT = HERE / "local-results"

# Exact H1D10A production-of-label rules, copied for diagnostic reproduction.
TITLES = [
    ("NOTA_CREDITO", r"NOTA (?:DE )?CREDITO(?: ELECTRONICA)?"),
    ("NOTA_DEBITO", r"NOTA (?:DE )?DEBITO(?: ELECTRONICA)?"),
    ("FACTURA", r"FACTURA(?: DE CREDITO ELECTRONICA(?: MIPYMES)?)?(?: ELECTRONICA)?"),
    ("RECIBO", r"RECIBO(?: DE (?:PAGO|COBRO|SUELDO))?"),
    ("TRANSFERENCIA_ANTICIPO", r"SOLICITUD DE (?:TRANSFERENCIA|ANTICIPO)"),
    ("COMPROBANTE_BANCARIO", r"(?:COMPROBANTE|BOLETA) DE (?:DEPOSITO|TRANSFERENCIA)"),
    ("IMPUESTO_BOLETA", r"(?:IMPUESTO (?:INMOBILIARIO|AUTOMOTOR|A LOS INGRESOS BRUTOS)|BOLETA DE (?:PAGO|DEUDA))"),
]
SUFFIX = r"(?:\s+(?:[ABCEM]|(?:N[RO°º.]*|NUMERO|COD(?:IGO)?|COD\.)\s*[:.\-]?|\d[\d\s./:\-]*|ORIGINAL|DUPLICADO|TRIPLICADO))*"

# Diagnostic lexical cues. These are intentionally NOT used as labels.
# Their only purpose is to tell us whether the saved text contains the kind of
# wording a human visual reviewer associated with the document.
CUES = {
    "FACTURA": [r"\bFACTURA\b"],
    "NOTA_CREDITO": [r"\bNOTA\s+(?:DE\s+)?CREDITO\b"],
    "NOTA_DEBITO": [r"\bNOTA\s+(?:DE\s+)?DEBITO\b"],
    "RECIBO": [r"\bRECIBO\b"],
    "TRANSFERENCIA_ANTICIPO": [
        r"\bSOLICITUD\s+DE\s+(?:TRANSFERENCIA|ANTICIPO)\b",
        r"\bTRANSFERENCIA\b",
        r"\bANTICIPO\b",
    ],
    "COMPROBANTE_BANCARIO": [
        r"\bCOMPROBANTE\s+DE\s+(?:TRANSFERENCIA|DEPOSITO)\b",
        r"\bBOLETA\s+DE\s+DEPOSITO\b",
        r"\bTRANSFERENCIA\b",
        r"\bDEPOSITO\b",
    ],
    "IMPUESTO_BOLETA": [
        r"\bIMPUESTO\s+(?:INMOBILIARIO|AUTOMOTOR|A\s+LOS\s+INGRESOS\s+BRUTOS)\b",
        r"\bBOLETA\s+DE\s+(?:PAGO|DEUDA)\b",
    ],
}


def norm(value: str) -> str:
    value = "".join(
        c for c in unicodedata.normalize("NFKD", (value or "").upper())
        if not unicodedata.combining(c)
    )
    return re.sub(r"[ \t]+", " ", value).strip()


def flat(value: str) -> str:
    return re.sub(r"\s+", " ", norm(value)).strip()


def strict_title_evidence(header: str, confidence: float):
    if confidence < 0.80:
        return []
    found = []
    for line in (header or "").splitlines():
        line = norm(line).strip(" |:")
        for typ, pat in TITLES:
            if re.fullmatch(
                r"(?:ORIGINAL\s+|DUPLICADO\s+|TRIPLICADO\s+)?" + pat + SUFFIX,
                line,
            ):
                found.append(typ)
    return sorted(set(found))


def read_csv(path: Path):
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows, fields):
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def read_text(path: Path | None) -> str:
    if path is None or not path.exists():
        return ""
    return path.read_text(encoding="utf-8-sig", errors="replace")


def resolve_asset(stored: str, sha: str, role: str) -> Path | None:
    """Resolve absolute paths from the original run or rebase into H1D10A/text."""
    if stored:
        p = Path(stored)
        if p.exists():
            return p
    text_dir = H1D10A / "text"
    candidates = []
    if role == "header":
        candidates = [text_dir / f"{sha}.header.txt"]
    elif role == "native":
        candidates = [text_dir / f"{sha}.native.txt"]
    elif role == "text":
        candidates = [
            text_dir / f"{sha}.native.txt",
            text_dir / f"{sha}.ocr.txt",
            text_dir / f"{sha}.header.txt",
        ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return None


def boolish(value: str) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "si", "sí"}


def intish(value: str) -> int:
    try:
        return int(float(value))
    except Exception:
        return 0


def floatish(value: str) -> float:
    try:
        return float(value)
    except Exception:
        return 0.0


def find_cue(reference_type: str, text: str):
    value = flat(text)
    for pattern in CUES.get(reference_type, []):
        match = re.search(pattern, value)
        if match:
            return match.group(0), match.start(), value
    return "", -1, value


def snippet(value: str, pos: int, radius: int = 120) -> str:
    if pos < 0:
        return ""
    lo = max(0, pos - radius)
    hi = min(len(value), pos + radius)
    return value[lo:hi]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest().upper()


def classify(reference_type: str, strict, header_cue: str, full_cue: str,
             native_cue: str, header_conf: float, header_exists: bool,
             full_exists: bool) -> str:
    if reference_type == "OTRO_DOCUMENTO":
        return "SEMANTIC_OR_NON_TITLE_DOCUMENT"
    if strict:
        return "STRICT_RULE_MATCH_UNEXPECTED"
    if header_cue:
        return "HEADER_CUE_PRESENT_RULE_REJECTED"
    if full_cue:
        return "CUE_PRESENT_OUTSIDE_HEADER_OR_HEADER_OCR_MISSED"
    if native_cue:
        return "CUE_PRESENT_NATIVE_ONLY"
    if header_conf < 0.80:
        return "LOW_HEADER_OCR_CONFIDENCE"
    if not header_exists or not full_exists:
        return "LOCAL_TEXT_ASSET_MISSING"
    return "NO_EXPECTED_CUE_IN_SAVED_TEXT"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(DEFAULT_OUT))
    parser.add_argument("--verify-images", action="store_true",
                        help="Verify existence/hash of the 150 blind source images on E: (optional).")
    args = parser.parse_args()
    out = Path(args.output).resolve()
    out.mkdir(parents=True, exist_ok=True)

    required = {
        "bank": H1D10A / "bank-manifest.csv",
        "top": H1D10B / "review-top150.csv",
        "trace": H1D10B / "b3-blind-traceability.csv",
        "visual": H1D10B / "ReviewTop150-evaluacion-visual-ciega-ChatGPT.csv",
    }
    missing = [str(p) for p in required.values() if not p.exists()]
    if missing:
        raise SystemExit("Missing required tracked inputs:\n" + "\n".join(missing))

    bank = {r["Sha256"].upper(): r for r in read_csv(required["bank"])}
    top = {r["CandidateId"]: r for r in read_csv(required["top"])}
    trace = {r["CandidateId"]: r for r in read_csv(required["trace"])}
    visual = {r["CandidateId"]: r for r in read_csv(required["visual"])}

    ids = sorted(set(top) & set(trace) & set(visual))
    if len(ids) != 150:
        raise SystemExit(f"Expected 150 aligned candidates; found {len(ids)}")

    rows = []
    for cid in ids:
        t = top[cid]
        v = visual[cid]
        tr = trace[cid]
        sha = t["Sha256"].upper()
        b = bank.get(sha)
        if b is None:
            raise SystemExit(f"{cid}: SHA missing from bank-manifest: {sha}")

        header_path = resolve_asset(b.get("HeaderTextAsset", ""), sha, "header")
        text_path = resolve_asset(b.get("TextAsset", ""), sha, "text")
        native_path = resolve_asset(b.get("NativeTextAsset", ""), sha, "native")
        header_text = read_text(header_path)
        full_text = read_text(text_path)
        native_text = read_text(native_path)
        header_conf = floatish(b.get("HeaderOcrConfidence", ""))
        strict = strict_title_evidence(header_text, header_conf)

        reference_type = v.get("DocumentType", "")
        hcue, hpos, hflat = find_cue(reference_type, header_text)
        fcue, fpos, fflat = find_cue(reference_type, full_text)
        ncue, npos, nflat = find_cue(reference_type, native_text)
        category = classify(
            reference_type, strict, hcue, fcue, ncue, header_conf,
            header_path is not None and header_path.exists(),
            text_path is not None and text_path.exists(),
        )

        image_path = Path(tr.get("SourceAsset", "")) if tr.get("SourceAsset") else None
        image_exists = bool(image_path and image_path.exists())
        image_hash_ok = ""
        if args.verify_images and image_exists:
            image_hash_ok = str(sha256(image_path) == tr.get("AssetSha256", "").upper())

        rows.append({
            "CandidateId": cid,
            "Sha256": sha,
            "FileName": b.get("FileName", ""),
            "VisualReferenceType": reference_type,
            "VisualReferenceLabel": v.get("LabelFinal", ""),
            "VisualObservation": v.get("Observacion", ""),
            "DiagnosticCategory": category,
            "TextMethod": b.get("TextMethod", ""),
            "NativeUseful": b.get("NativeUseful", ""),
            "HeaderOcrConfidence": b.get("HeaderOcrConfidence", ""),
            "TextCharactersManifest": b.get("TextCharacters", ""),
            "StrictTitleTypesRecomputed": ";".join(strict),
            "HeaderCue": hcue,
            "FullTextCue": fcue,
            "NativeCue": ncue,
            "HeaderTextExists": str(bool(header_path and header_path.exists())),
            "TextAssetExists": str(bool(text_path and text_path.exists())),
            "NativeTextExists": str(bool(native_path and native_path.exists())),
            "HeaderTextPathResolved": str(header_path or ""),
            "TextPathResolved": str(text_path or ""),
            "NativeTextPathResolved": str(native_path or ""),
            "HeaderCueSnippet": snippet(hflat, hpos),
            "FullCueSnippet": snippet(fflat, fpos),
            "NativeCueSnippet": snippet(nflat, npos),
            "BlindImageExists": str(image_exists),
            "BlindImageHashOk": image_hash_ok,
            "FamilyId": b.get("FamilyId", ""),
            "FamilyTrainingCount": t.get("FamilyTrainingCount", ""),
            "QualityStatus": b.get("QualityStatus", ""),
        })

    fields = list(rows[0].keys())
    write_csv(out / "cases.csv", rows, fields)

    categories = Counter(r["DiagnosticCategory"] for r in rows)
    types = Counter(r["VisualReferenceType"] for r in rows)
    methods = Counter(r["TextMethod"] for r in rows)
    assets = {
        "HeaderTextPresent": sum(r["HeaderTextExists"] == "True" for r in rows),
        "TextAssetPresent": sum(r["TextAssetExists"] == "True" for r in rows),
        "NativeTextPresent": sum(r["NativeTextExists"] == "True" for r in rows),
        "BlindImagesPresent": sum(r["BlindImageExists"] == "True" for r in rows),
    }
    high_conf = sum(floatish(r["HeaderOcrConfidence"]) >= .80 for r in rows)
    native_useful = sum(boolish(r["NativeUseful"]) for r in rows)

    per_type = {}
    for typ in sorted(types):
        rr = [r for r in rows if r["VisualReferenceType"] == typ]
        per_type[typ] = {
            "Count": len(rr),
            "HeaderConfidenceGe080": sum(floatish(r["HeaderOcrConfidence"]) >= .80 for r in rr),
            "NativeUseful": sum(boolish(r["NativeUseful"]) for r in rr),
            "Categories": dict(Counter(r["DiagnosticCategory"] for r in rr)),
        }

    summary = {
        "Experiment": "H1D10C",
        "Purpose": "Perception/title diagnostic only; no training and no production labels.",
        "Candidates": len(rows),
        "VisualReferenceIsGroundTruth": False,
        "HeaderConfidenceGe080": high_conf,
        "NativeUseful": native_useful,
        "TrackedManifestStrictTitleEvidenceExpected": 0,
        "StrictTitleMatchesRecomputed": sum(bool(r["StrictTitleTypesRecomputed"]) for r in rows),
        "AssetAvailability": assets,
        "TextMethods": dict(methods),
        "VisualReferenceTypes": dict(types),
        "DiagnosticCategories": dict(categories),
        "PerType": per_type,
    }
    (out / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [
        "# H1D10C — Auditoría de percepción documental",
        "",
        "Diagnóstico solamente. No entrena, no modifica modelos y no convierte la revisión visual de ChatGPT en ground truth.",
        "",
        f"- Casos alineados: **{len(rows)}**",
        f"- OCR de cabecera >= 0,80: **{high_conf}/{len(rows)}**",
        f"- Texto nativo Mdoc marcado útil: **{native_useful}/{len(rows)}**",
        f"- Regla estricta de título reproducida: **{summary['StrictTitleMatchesRecomputed']}/{len(rows)}**",
        f"- Assets de texto de cabecera disponibles localmente: **{assets['HeaderTextPresent']}/{len(rows)}**",
        f"- Assets de texto principal disponibles localmente: **{assets['TextAssetPresent']}/{len(rows)}**",
        f"- Imágenes fuente de la revisión presentes: **{assets['BlindImagesPresent']}/{len(rows)}**",
        "",
        "## Categorías diagnósticas",
        "",
    ]
    for key, value in sorted(categories.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"- `{key}`: **{value}**")
    lines += ["", "## Por tipo visual de referencia", ""]
    for typ, data in per_type.items():
        lines.append(
            f"- `{typ}`: {data['Count']} casos; header>=0,80 {data['HeaderConfidenceGe080']}; "
            f"Mdoc útil {data['NativeUseful']}; categorías {json.dumps(data['Categories'], ensure_ascii=False)}"
        )
    lines += [
        "",
        "## Interpretación de categorías",
        "",
        "- `HEADER_CUE_PRESENT_RULE_REJECTED`: la frase diagnóstica está en el OCR de cabecera, pero la regla estricta no la acepta. Señala rigidez de formato/línea, no falta de lectura.",
        "- `CUE_PRESENT_OUTSIDE_HEADER_OR_HEADER_OCR_MISSED`: la frase está en el texto principal pero no en el OCR de cabecera. Señala crop/posición/OCR de cabecera o layout.",
        "- `CUE_PRESENT_NATIVE_ONLY`: la frase aparece en texto nativo Mdoc pero no en el texto principal seleccionado/cabecera.",
        "- `LOW_HEADER_OCR_CONFIDENCE`: OCR de cabecera por debajo del gate 0,80.",
        "- `NO_EXPECTED_CUE_IN_SAVED_TEXT`: la referencia visual es de un tipo explícito pero esa frase no aparece en los textos guardados; requiere inspección visual/textual antes de culpar Mdoc u OCR.",
        "- `SEMANTIC_OR_NON_TITLE_DOCUMENT`: OTRO_DOCUMENTO genérico; por definición no se espera resolverlo con una sola regla de título.",
        "",
        "El detalle local, incluidos snippets de texto, queda en `cases.csv` y no debe versionarse automáticamente.",
    ]
    (out / "resultado.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("H1D10C completed")
    print(f"Candidates: {len(rows)}")
    print(f"Header confidence >= 0.80: {high_conf}")
    print(f"Native useful: {native_useful}")
    print(f"Strict title matches: {summary['StrictTitleMatchesRecomputed']}")
    print(f"Header text assets present: {assets['HeaderTextPresent']}")
    print(f"Main text assets present: {assets['TextAssetPresent']}")
    print("Categories:")
    for key, value in sorted(categories.items(), key=lambda kv: (-kv[1], kv[0])):
        print(f"  {key}: {value}")
    print(f"Output: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
